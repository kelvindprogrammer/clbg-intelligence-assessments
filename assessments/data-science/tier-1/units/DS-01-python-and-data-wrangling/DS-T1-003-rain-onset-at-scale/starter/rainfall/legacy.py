"""LEGACY agro-climate indices: correct, readable, and far too slow.

These functions ARE the specification. Your fast versions in fast.py must return the same
values (see README section D for the exact equivalence rules) on any valid input.
Do not edit this file: the tests compare your code against it.

Input to every function: a DataFrame with columns station_id (str), date (datetime64),
rain_mm (float64, NaN = missing reading), as returned by load_rainfall(). Rows may be
in any order, and a day may be absent altogether. An absent day is treated exactly
like a day whose reading is missing.

"Years of a station" always means the calendar years in which that station has at
least one row.
"""
from __future__ import annotations

import calendar
import datetime as dt
import math

import pandas as pd

WET_DAY_MM = 1.0           # a day with rain >= 1 mm is "wet"
ONSET_3DAY_MM = 20.0       # onset needs >= 20 mm over the candidate day and the next two
ONSET_DRY_SPELL = 7        # ...and no run of 7+ non-wet days in the 30 days that follow
ONSET_LOOKAHEAD = 30
ONSET_SEARCH = ((3, 1), (7, 31))       # candidate days: 1 March to 31 July
DRY_SPELL_WINDOW = ((4, 1), (10, 31))  # dry-spell season: 1 April to 31 October
MIN_CLIM_YEARS = 3


def _by_station(df: pd.DataFrame) -> dict[str, dict[dt.date, float]]:
    data: dict[str, dict[dt.date, float]] = {}
    for row in df.itertuples(index=False):
        data.setdefault(row.station_id, {})[row.date.date()] = row.rain_mm
    return data


def _value(days: dict[dt.date, float], d: dt.date) -> float | None:
    v = days.get(d)
    if v is None or math.isnan(v):
        return None
    return v


def _daterange(start: dt.date, end: dt.date):
    d = start
    while d <= end:
        yield d
        d += dt.timedelta(days=1)


def monthly_totals(df: pd.DataFrame) -> pd.DataFrame:
    """Monthly rainfall per station, for all 12 months of every year of the station.

    Columns: station_id, year, month, total_mm, n_missing.
    n_missing counts the days of the month with no valid reading (absent or NaN).
    total_mm is the sum of the readings, or NaN if n_missing > 0.
    Sorted by station_id, year, month.
    """
    rows = []
    for station, days in sorted(_by_station(df).items()):
        for year in sorted({d.year for d in days}):
            for month in range(1, 13):
                total, missing = 0.0, 0
                for day in range(1, calendar.monthrange(year, month)[1] + 1):
                    v = _value(days, dt.date(year, month, day))
                    if v is None:
                        missing += 1
                    else:
                        total += v
                rows.append((station, year, month, total if missing == 0 else math.nan, missing))
    out = pd.DataFrame(rows, columns=["station_id", "year", "month", "total_mm", "n_missing"])
    return out.astype({"year": "int64", "month": "int64", "total_mm": "float64", "n_missing": "int64"})


def longest_dry_spell(df: pd.DataFrame) -> pd.DataFrame:
    """Longest run of consecutive non-wet days (rain < 1 mm) between 1 April and 31 October.

    A missing day ends a run and is not counted in any run.
    Columns: station_id, year, longest_dry_spell (int64). Sorted by station_id, year.
    """
    (m0, d0), (m1, d1) = DRY_SPELL_WINDOW
    rows = []
    for station, days in sorted(_by_station(df).items()):
        for year in sorted({d.year for d in days}):
            best = run = 0
            for d in _daterange(dt.date(year, m0, d0), dt.date(year, m1, d1)):
                v = _value(days, d)
                if v is not None and v < WET_DAY_MM:
                    run += 1
                    best = max(best, run)
                else:
                    run = 0
            rows.append((station, year, best))
    return pd.DataFrame(rows, columns=["station_id", "year", "longest_dry_spell"]).astype({"year": "int64",
                                                                                            "longest_dry_spell": "int64"})


def onset_dates(df: pd.DataFrame) -> pd.DataFrame:
    """Onset of the rains per station and year (an agronomic "false start"-resistant rule).

    The onset is the FIRST day d between 1 March and 31 July such that:
      1. the readings for d, d+1 and d+2 are all valid, d is wet (>= 1 mm), and their sum >= 20 mm;
      2. in the 30 days d+1 .. d+30 there is no run of 7 or more consecutive days that are
         non-wet OR missing (missing days are treated as dry: the conservative choice);
      3. d+30 is not later than the station's last date in the data (the look-ahead is complete).
    Columns: station_id, year, onset_date (datetime64, NaT if no onset), onset_doy (Int64, <NA> if none).
    Sorted by station_id, year.
    """
    (m0, d0), (m1, d1) = ONSET_SEARCH
    rows = []
    for station, days in sorted(_by_station(df).items()):
        last = max(days)
        for year in sorted({d.year for d in days}):
            onset = None
            for d in _daterange(dt.date(year, m0, d0), dt.date(year, m1, d1)):
                r = [_value(days, d + dt.timedelta(days=k)) for k in range(3)]
                if any(v is None for v in r) or r[0] < WET_DAY_MM or sum(r) < ONSET_3DAY_MM:
                    continue
                if d + dt.timedelta(days=ONSET_LOOKAHEAD) > last:
                    continue
                run, ok = 0, True
                for k in range(1, ONSET_LOOKAHEAD + 1):
                    v = _value(days, d + dt.timedelta(days=k))
                    if v is None or v < WET_DAY_MM:
                        run += 1
                        if run >= ONSET_DRY_SPELL:
                            ok = False
                            break
                    else:
                        run = 0
                if ok:
                    onset = d
                    break
            rows.append((station, year, pd.Timestamp(onset) if onset else pd.NaT,
                         onset.timetuple().tm_yday if onset else pd.NA))
    out = pd.DataFrame(rows, columns=["station_id", "year", "onset_date", "onset_doy"])
    out["onset_date"] = pd.to_datetime(out["onset_date"]).astype("datetime64[ns]")
    return out.astype({"year": "int64", "onset_doy": "Int64"})


def standardised_anomalies(df: pd.DataFrame) -> pd.DataFrame:
    """Monthly totals with each month's standardised anomaly against the station's own climatology.

    Starting from monthly_totals(df), for each (station_id, month): clim_mean and clim_std
    (sample standard deviation, ddof=1) of total_mm over the years where total_mm is not NaN.
    If fewer than 3 such years exist, both are NaN. z = (total_mm - clim_mean) / clim_std,
    and NaN when total_mm is NaN, clim_std is NaN, or clim_std == 0.
    Columns: the monthly_totals columns + clim_mean, clim_std, z. Same row order as monthly_totals.
    """
    mt = monthly_totals(df)
    stats: dict[tuple[str, int], tuple[float, float]] = {}
    for (station, month) in {(s, m) for s, m in zip(mt["station_id"], mt["month"])}:
        vals = [v for s, m, v in zip(mt["station_id"], mt["month"], mt["total_mm"])
                if s == station and m == month and not math.isnan(v)]
        if len(vals) < MIN_CLIM_YEARS:
            stats[(station, month)] = (math.nan, math.nan)
            continue
        mean = sum(vals) / len(vals)
        std = math.sqrt(sum((v - mean) ** 2 for v in vals) / (len(vals) - 1))
        stats[(station, month)] = (mean, std)
    means, stds, zs = [], [], []
    for s, m, v in zip(mt["station_id"], mt["month"], mt["total_mm"]):
        mean, std = stats[(s, m)]
        means.append(mean)
        stds.append(std)
        zs.append(math.nan if (math.isnan(v) or math.isnan(std) or std == 0) else (v - mean) / std)
    mt["clim_mean"], mt["clim_std"], mt["z"] = means, stds, zs
    return mt
