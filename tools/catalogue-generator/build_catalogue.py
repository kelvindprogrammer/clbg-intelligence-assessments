#!/usr/bin/env python3
"""Build the CLBG assessment catalogue and navigation indexes from metadata.

Files written (all generated, do not edit by hand):
  CATALOGUE.md                                   full searchable catalogue
  catalogue.json                                 machine-readable catalogue
  docs/catalogue/coverage-matrix.md              planned vs built, by unit and tier
  docs/catalogue/by-format.md                    assessments grouped by format
  docs/catalogue/by-domain.md                    assessments grouped by domain
  assessments/<subtrack>/tier-N/README.md        tier landing pages
  assessments/<subtrack>/tier-N/units/<unit>/README.md   unit landing pages
  assessments/<subtrack>/README.md               only the block between markers

Usage:
  python tools/catalogue-generator/build_catalogue.py          # write
  python tools/catalogue-generator/build_catalogue.py --check  # exit 1 if anything is stale
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "lib"))
import clbgtools as ct  # noqa: E402

GEN_NOTE = "<!-- GENERATED by tools/catalogue-generator/build_catalogue.py: do not edit by hand -->"
START, END = "<!-- CATALOGUE:START -->", "<!-- CATALOGUE:END -->"

TIER_NAMES = {
    1: "Tier 1: Foundation and Technical Fluency",
    2: "Tier 2: Applied Engineering and Independent Problem-Solving",
    3: "Tier 3: Advanced Engineering, Research and System Design",
}
TIER_BLURB = {
    1: "Can you understand the fundamentals and independently implement a correct, explained, reproducible solution to a well-specified problem?",
    2: "Can you independently solve a realistic, partially specified problem, choosing and justifying methods, testing your work and reasoning about its limits?",
    3: "Can you take on an ambiguous, substantial problem, make research-informed decisions, run rigorous experiments, and defend the trade-offs?",
}
FORMAT_NAMES = {
    "implementation": "Implementation", "investigation": "Investigation",
    "reverse-engineering": "Reverse Engineering", "replication": "Research Replication",
    "comparative": "Comparative", "optimization": "Optimization",
    "system-design": "System Design", "debugging-forensics": "Debugging & Forensics",
    "open-ended": "Open-Ended",
}


def rel(from_file: Path, to: Path) -> str:
    return Path(os.path.relpath(to, from_file.parent)).as_posix()


def hours(m: dict) -> str:
    h = m.get("estimated_hours") or {}
    return f"{h.get('min', '?')}–{h.get('max', '?')} h"


def diff_str(m: dict) -> str:
    d = m.get("difficulty") or {}
    return " ".join(f"{k[0].upper()}{d.get(k, '?')}" for k in ["technical", "mathematical", "research", "engineering", "ambiguity", "resources"])


def compute_str(m: dict) -> str:
    c = m.get("compute") or {}
    bits = []
    if c.get("gpu") and c["gpu"] != "none":
        bits.append(f"GPU {c['gpu']}")
    if c.get("paid_api") and c["paid_api"] != "none":
        bits.append(f"paid API {c['paid_api']}")
    if c.get("internet") == "required":
        bits.append("online")
    return ", ".join(bits) or "CPU, offline-capable"


def table(rows, here: Path, cols=("id", "title", "unit", "format", "hours", "status")) -> str:
    head = {"id": "ID", "title": "Title", "unit": "Unit", "tier": "Tier", "format": "Format", "hours": "Est. time",
            "status": "Status", "subtrack": "Subtrack", "domain": "Domain", "compute": "Compute", "difficulty": "Difficulty (T M R E A Res)"}
    out = ["| " + " | ".join(head[c] for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for a in rows:
        m = a.meta
        cells = []
        for c in cols:
            if c == "id":
                cells.append(f"[`{m['id']}`]({rel(here, a.path / 'README.md')})")
            elif c == "title":
                cells.append(m["title"].replace("|", "\\|"))
            elif c == "format":
                cells.append(FORMAT_NAMES.get(m["format"], m["format"]))
            elif c == "hours":
                cells.append(hours(m))
            elif c == "domain":
                cells.append(", ".join(m.get("domains", [])))
            elif c == "compute":
                cells.append(compute_str(m))
            elif c == "difficulty":
                cells.append(diff_str(m))
            else:
                cells.append(str(m.get(c, "")))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def sort_key(a):
    return a.meta.get("id", "")


def build(check: bool) -> int:
    units = ct.load_units()
    subtracks = ct.load_subtracks()
    assessments = [a for a in ct.load_assessments() if a.meta.get("id")]
    assessments.sort(key=sort_key)
    outputs: dict[Path, str] = {}
    root = ct.ROOT

    by_sub_tier_unit = defaultdict(list)
    for a in assessments:
        m = a.meta
        by_sub_tier_unit[(m["subtrack"], m["tier"], m["unit"])].append(a)

    # ---------- unit and tier landing pages
    for sub, sinfo in subtracks.items():
        sub_dir = root / "assessments" / sub
        for tier in (1, 2, 3):
            tier_dir = sub_dir / f"tier-{tier}"
            tier_readme = tier_dir / "README.md"
            lines = [GEN_NOTE, f"# {sinfo['name']}: {TIER_NAMES[tier]}", "",
                     f"> **The question this tier answers:** {TIER_BLURB[tier]}", "",
                     f"See [tier definitions]({rel(tier_readme, root / 'docs' / 'tier-definitions.md')}) for the full competency description, "
                     f"and [how to choose an assessment]({rel(tier_readme, root / 'docs' / 'member-handbook.md')}).", "",
                     "## Units at this tier", ""]
            for code, u in units.items():
                if u["subtrack"] != sub:
                    continue
                target = int(u["targets"].get(tier, 0))
                unit_dir = tier_dir / "units" / f"{code}-{u['slug']}"
                items = by_sub_tier_unit.get((sub, tier, code), [])
                if target == 0:
                    lines.append(f"### {code}: {u['name']}\n\n_Not offered at this tier._ {u.get('tier_notes', '')}\n")
                    continue
                if items:
                    lines.append(f"### [{code}: {u['name']}]({rel(tier_readme, unit_dir / 'README.md')})\n\n{u['description']}\n")
                else:
                    lines.append(f"### {code}: {u['name']}\n\n{u['description']}\n")
                if items:
                    lines.append(table(items, tier_readme, ("id", "title", "format", "hours", "status")))
                    lines.append("")
                else:
                    lines.append("_Assessments for this unit are in development._\n")
                # unit page
                if items:
                    unit_readme = unit_dir / "README.md"
                    ul = [GEN_NOTE, f"# {code}: {u['name']} ({TIER_NAMES[tier].split(':')[0]})", "",
                          f"**Subtrack:** {sinfo['name']}  ", f"**Unit scope:** {u['description']}", ""]
                    if u.get("tier_notes"):
                        ul += [f"**Tier note:** {u['tier_notes']}", ""]
                    ul += ["## Assessments", "",
                           "Pick **any one**. Every assessment here is an independent, complete demonstration of this unit at this tier.", "",
                           table(items, unit_readme, ("id", "title", "format", "domain", "hours", "compute", "difficulty")), ""]
                    for a in items:
                        ul.append(f"- **[{a.meta['id']}]({rel(unit_readme, a.path / 'README.md')}): {a.meta['title']}.** {a.meta['summary']}")
                    other = [t for t in (1, 2, 3) if t != tier and by_sub_tier_unit.get((sub, t, code))]
                    if other:
                        ul += ["", "## Same unit, other tiers", ""]
                        for t in other:
                            ul.append(f"- [Tier {t}]({rel(unit_readme, sub_dir / f'tier-{t}' / 'units' / (code + '-' + u['slug']) / 'README.md')})")
                    outputs[unit_readme] = "\n".join(ul) + "\n"
            outputs[tier_readme] = "\n".join(lines) + "\n"

        # subtrack README generated block
        sub_readme = sub_dir / "README.md"
        if sub_readme.exists():
            block = [START, "", "## Assessment map", "", "| Unit | Tier 1 | Tier 2 | Tier 3 |", "|---|---|---|---|"]
            for code, u in units.items():
                if u["subtrack"] != sub:
                    continue
                cells = []
                for t in (1, 2, 3):
                    n_built = len(by_sub_tier_unit.get((sub, t, code), []))
                    if int(u["targets"].get(t, 0)) == 0:
                        cells.append("—")
                    elif n_built:
                        cells.append(f"[{n_built} assessment{'s' if n_built != 1 else ''}]({rel(sub_readme, sub_dir / f'tier-{t}' / 'units' / (code + '-' + u['slug']) / 'README.md')})")
                    else:
                        cells.append("in development")
                block.append(f"| **{code}** {u['name']} | " + " | ".join(cells) + " |")
            block += ["", END]
            text = sub_readme.read_text(encoding="utf-8")
            if START in text and END in text:
                pre, rest = text.split(START, 1)
                _, post = rest.split(END, 1)
                outputs[sub_readme] = pre + "\n".join(block) + post

    # ---------- full catalogue
    cat = root / "CATALOGUE.md"
    lines = [GEN_NOTE, "# CLBG Intelligence Track: Assessment Catalogue", "",
             f"**{len(assessments)} assessments.** Use your browser's find (Ctrl/Cmd+F) to search by ID, title, technology or domain, "
             "or filter [`catalogue.json`](catalogue.json) programmatically.", "",
             "Difficulty is rated 1–5 on six independent dimensions: **T**echnical, **M**athematical, **R**esearch, **E**ngineering, "
             "**A**mbiguity and **Res**ources. See [tier definitions](docs/tier-definitions.md#5-multi-dimensional-difficulty).", "",
             "Other views: [coverage matrix](docs/catalogue/coverage-matrix.md) · [by format](docs/catalogue/by-format.md) · [by domain](docs/catalogue/by-domain.md)", ""]
    sections = [("data-science", "unit"), ("ml-engineering", "unit"), ("ai-engineering", "unit")]
    for sub, _ in sections:
        lines.append(f"## {subtracks[sub]['name']}")
        for t in (1, 2, 3):
            items = [a for a in assessments if a.meta["subtrack"] == sub and a.meta["tier"] == t and a.meta["collection"] == "unit"]
            if items:
                lines += ["", f"### {TIER_NAMES[t]}", "", table(items, cat, ("id", "title", "unit", "format", "domain", "hours", "difficulty", "status"))]
        lines.append("")
    outputs[cat] = "\n".join(lines) + "\n"

    # json
    records = []
    for a in assessments:
        rec = {k: a.meta.get(k) for k in ("id", "title", "summary", "version", "status", "collection", "subtrack", "tier", "unit",
                                         "format", "secondary_formats", "domains", "technologies", "competencies",
                                         "estimated_hours", "difficulty", "compute", "collaboration", "datasets", "tags")}
        rec["path"] = a.rel
        records.append(rec)
    outputs[root / "catalogue.json"] = json.dumps({"generated_by": "tools/catalogue-generator/build_catalogue.py",
                                                   "count": len(records), "assessments": records}, indent=2, default=str) + "\n"

    # coverage matrix
    cov = root / "docs" / "catalogue" / "coverage-matrix.md"
    cl = [GEN_NOTE, "# Coverage Matrix", "", "Built assessments versus the planned target, per unit and tier, from `shared/units.yaml`. "
          "`—` means the tier is intentionally not offered for that unit; the reason is recorded in the unit registry.", ""]
    tot_t = tot_b = 0
    for sub, sinfo in subtracks.items():
        cl += [f"## {sinfo['name']}", "", "| Unit | T1 built/target | T2 built/target | T3 built/target |", "|---|---|---|---|"]
        for code, u in units.items():
            if u["subtrack"] != sub:
                continue
            cells = []
            for t in (1, 2, 3):
                tg = int(u["targets"].get(t, 0))
                b = len(by_sub_tier_unit.get((sub, t, code), []))
                tot_t += tg
                tot_b += min(b, tg) if tg else 0
                cells.append("—" if tg == 0 and b == 0 else f"{b}/{tg}" + (" ✅" if b >= tg and tg else ""))
            cl.append(f"| {code} {u['name']} | " + " | ".join(cells) + " |")
        cl.append("")
    cl += ["## Totals", "", f"- Unit assessments built against target: **{tot_b}/{tot_t}**",
           f"- **Total assessments: {len(assessments)}**", ""]
    outputs[cov] = "\n".join(cl) + "\n"

    # by format / by domain
    for fname, key, label in (("by-format.md", "format", "Format"), ("by-domain.md", "domains", "Domain")):
        p = root / "docs" / "catalogue" / fname
        groups = defaultdict(list)
        for a in assessments:
            vals = a.meta.get(key)
            vals = vals if isinstance(vals, list) else [vals]
            for v in vals:
                groups[v].append(a)
        gl = [GEN_NOTE, f"# Assessments by {label}", ""]
        for g in sorted(groups, key=str):
            gl += [f"## {FORMAT_NAMES.get(g, str(g).replace('-', ' ').title())} ({len(groups[g])})", "",
                   table(groups[g], p, ("id", "title", "subtrack", "tier", "hours")), ""]
        outputs[p] = "\n".join(gl) + "\n"

    stale = []
    for path, content in outputs.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != content:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("Catalogue is stale. Run build_catalogue.py. Stale files:")
            for s in stale:
                print("  " + s.relative_to(root).as_posix())
            return 1
        print(f"Catalogue up to date ({len(assessments)} assessments).")
        return 0
    print(f"Wrote {len(stale)} file(s); catalogue covers {len(assessments)} assessments.")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(build(ap.parse_args().check))
